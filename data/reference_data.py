def get_country_iso(country_name, default=None):
    """Lookup ISO 2-letter code by country name (case-insensitive, with common aliases)."""
    if not country_name:
        return default
    c_lower = country_name.strip().lower()
    if c_lower in COUNTRY_ALIASES:
        return COUNTRY_ALIASES[c_lower]
    for name, code in COUNTRY_TO_ISO.items():
        if name.lower() == c_lower:
            return code
    return default


def get_country_name(iso_code, default=None):
    """Lookup country name by 2-letter ISO code (case-insensitive)."""
    if not iso_code:
        return default
    return ISO_TO_COUNTRY.get(iso_code.strip().upper(), default)


def get_hs_code(product_name, default=None):
    """
    Lookup HS code by product name.
    Performs case-insensitive exact match first, then substring match.
    """
    if not product_name:
        return default
    p_upper = product_name.strip().upper()
    for name, code in PRODUCT_TO_HS_CODE.items():
        if name.upper() == p_upper:
            return code
    for name, code in PRODUCT_TO_HS_CODE.items():
        if name.upper() in p_upper or p_upper in name.upper():
            return code
    return default


def get_product_by_hs(hs_code, default=None):
    """Lookup product name by HS code."""
    if not hs_code:
        return default
    return HS_CODE_TO_PRODUCT.get(str(hs_code).strip(), default)
